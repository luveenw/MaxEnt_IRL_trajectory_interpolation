#!/usr/bin/env bash
# Concatenate the shared covariate module with each app into paste-ready files.
#
# The Earth Engine Code Editor only resolves require() against a saved script
# repository, so for the copy-paste workflow the module has to be inlined. This
# produces gee/build/*.js -- open one, select all, paste into a Code Editor
# script, Run.
#
# Usage:  bash gee/build.sh

set -euo pipefail
DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
OUT="${DIR}/build"
mkdir -p "${OUT}"

for app in 01_biome_review_app 02_visualization_app; do
  {
    printf '// ============================================================\n'
    printf '// GENERATED by gee/build.sh -- do not edit.\n'
    printf '// Sources: gee/00_covariates.js + gee/%s.js\n' "${app}"
    printf '// ============================================================\n\n'
    cat "${DIR}/00_covariates.js"
    printf '\n\n'
    cat "${DIR}/${app}.js"
  } > "${OUT}/${app}.paste.js"
  printf 'built %s (%s lines)\n' \
    "gee/build/${app}.paste.js" "$(wc -l < "${OUT}/${app}.paste.js")"
done

echo
echo "Paste one of the files above into the Code Editor and set ASSET_ROOT."
